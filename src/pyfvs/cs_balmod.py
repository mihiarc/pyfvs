_CS_BALMOD_DEFAULT = (68.776678, 0.0142029220, 0.46704069)  # fallback to AB-family coefficients


def cs_balmod(species: str, dbh: float, ba: float, bal: float) -> float:
    """Fortran-faithful CS BALMOD competition modifier.

    GMOD is used by HTGF, DGF, and RGNTHW (REGENT LESTB) to temper
    growth predictions by relative stand position.

    Args:
        species: Two-letter species code (e.g., 'WO', 'RO').
        dbh: Tree diameter at breast height (inches, outside bark).
        ba: Total stand basal area (sq ft/acre), clamped to 200.
        bal: Basal area in larger trees (sq ft/acre).

    Returns:
        Growth modifier in [0.15, B3]. Approaches B3 as BAL→0 (and
        for small trees where TRBA→0, PART1→-∞, PART4→0).
    """
    b1, b2, b3 = _CS_BALMOD.get(species.upper(), _CS_BALMOD_DEFAULT)

    trba = dbh * dbh * 0.005454
    temba = min(ba, 200.0)

    denom = bal + trba
    if denom <= 0.0:
        # Fortran would divide by zero; treat as saturated competition
        # (B1/0 → +∞, PART1 → -∞, PART4 → 0, GMOD → B3).
        return max(0.15, b3)

    part1 = -(b1 / denom + b2 * dbh * dbh)
    part2 = math.sqrt(max(0.0, 1.0 - temba / 210.0))
    part3 = part1 * part2

    part4 = math.exp(part3) if part3 > -85.0 else 0.0
    gmod = b3 * (1.0 - part4)
    return max(0.15, gmod)
